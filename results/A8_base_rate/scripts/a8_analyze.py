"""
a8_analyze.py — everything downstream of the stored outputs, regenerated by one command:

  python scripts/a8_analyze.py [--B 2000]

Reads the no-injection baseline from the stored graded reports and the sweep from
raw/<model>.jsonl (graded here with the frozen scripts/eval.py grade_binary), writes
outputs.jsonl, tables/*.csv|md, figures/*.png, results.md.

Conventions (stated in every table):
  * Item = (event, variant). y = 1 for the original question (ground truth Yes), 0 for the
    perturbed question (ground truth No). Answer parsed by eval.grade_binary (frozen).
  * P(Yes) = confidence if the answer is Yes, 1 - confidence if No.
  * Metrics per (model, condition): accuracy on original items, accuracy on perturbed items,
    merged pooled accuracy (c_orig + c_pert)/(n_orig + n_pert), balanced accuracy
    (mean of the two class accuracies — the bias-corrected merged accuracy), fraction of
    Yes answers, mean confidence, mean P(Yes), ECE (10 equal-width bins, P(Yes) vs y),
    Brier (P(Yes) vs y). ECE_c / Brier_c score confidence-in-answer vs correctness.
  * PRIMARY item set per model = "common set": events whose BOTH variants have a parsed
    answer and a confidence in the baseline and at every X, so every point on a curve is
    the same items. The all-valid (per-condition) variant is written as a sensitivity table.
  * Bootstrap: B event-level (cluster) resamples, percentile CIs, one shared resample matrix
    per model so conditions and slopes are paired. Slope = OLS of the metric on X/100 across
    the five injected values (baseline excluded); CI from the same resamples.
"""
from __future__ import annotations
import argparse, json, math, os, sys, subprocess, hashlib
from collections import defaultdict
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
import a8_common as C
sys.path.insert(0, str(C.ROOT / "calibration_study"))
import metrics as M                      # A6's vectorised ECE/Brier (10 equal-width bins)
from eval import grade_binary            # frozen grader

CONDS = ["base"] + C.XS
METRICS = [("acc_orig", "Accuracy, original items (ground truth Yes)"),
           ("acc_pert", "Accuracy, perturbed items (ground truth No)"),
           ("acc_merged", "Merged pooled accuracy"),
           ("bal_acc", "Balanced accuracy (bias-corrected merged)"),
           ("frac_yes", "Fraction of Yes answers"),
           ("mean_conf", "Mean self-reported confidence"),
           ("mean_pyes", "Mean implied P(Yes)"),
           ("auroc", "AUROC of P(Yes) against the outcome (threshold-free discrimination)"),
           ("ece", "ECE (P(Yes) vs outcome, 10 bins)"),
           ("brier", "Brier score (P(Yes) vs outcome)"),
           ("ece_c", "ECE (confidence vs correctness)"),
           ("brier_c", "Brier (confidence vs correctness)"),
           ("echo_rate", "Share of responses whose confidence is within 0.05 of X/100 (numeric echo)")]
MIN_N = 20


def load_sweep(model: str) -> dict:
    """{(x, id, task): rec} graded with the frozen grader; last record wins on duplicates."""
    p = C.RAW / f"{model}.jsonl"
    out = {}
    if not p.exists():
        return out
    for l in open(p, encoding="utf-8"):
        if not l.strip():
            continue
        r = json.loads(l)
        gt = "Yes" if r["task"] == "binary" else "No"
        ans = conf = None; correct = None
        if r.get("answer") and not r.get("error") and not r.get("refusal"):
            g = grade_binary(str(r["answer"]), gt)
            ans = g["parsed_answer"] if g["parsed_answer"] in ("yes", "no") else None
            correct = bool(g["correct"]) if ans else None
            conf = r.get("confidence")
            if conf is not None:
                conf = float(conf)
                if not (0.0 <= conf <= 1.0):
                    conf = None
        out[(int(r["x"]), r["id"], r["task"])] = dict(r, answer_parsed=ans, correct=correct, conf=conf)
    return out


def item_table(model: str):
    """List of dicts: one per (cond, id, task) with answer/conf/correct/p_yes/valid flags."""
    base = C.load_baseline(model); sw = load_sweep(model); ids = C.load_sample()["ids"]
    rows = []
    for cond in CONDS:
        for i in ids:
            for task in ("binary", "binary_perturbed"):
                y = 1 if task == "binary" else 0
                if cond == "base":
                    b = base[(i, task)]
                    ans, conf, correct, status = b["answer"], b["confidence"], b["correct"], b["status"]
                else:
                    r = sw.get((cond, i, task))
                    if r is None:
                        ans = conf = correct = None; status = "not_run"
                    else:
                        ans, conf, correct = r["answer_parsed"], r["conf"], r["correct"]
                        status = ("refusal" if r.get("refusal") else "error" if r.get("error") else
                                  "truncated" if (ans is None and r.get("stop_reason") in ("length", "max_tokens")) else
                                  "unparseable" if ans is None else "ok")
                rows.append(dict(model=model, cond=cond, id=i, task=task, y=y, answer=ans, conf=conf, correct=correct,
                                 p_yes=C.p_yes(ans, conf), valid_ans=ans is not None, valid_conf=(ans is not None and conf is not None),
                                 status=status))
    return rows


def _arr(rows, key):
    return np.array([r[key] for r in rows], float)


def compute_metrics(rows, W, ev_index, cond="base"):
    """rows: items of ONE (model, cond) restricted to a valid set. W: (B, n_events) counts.
    Returns {metric: (point, lo, hi, n)} — point from the unweighted data, CI from W."""
    if not rows:
        return {k: (math.nan, math.nan, math.nan, 0) for k, _ in METRICS}, {}
    idx = np.array([ev_index[r["id"]] for r in rows]); w = W[:, idx]
    y = _arr(rows, "y"); corr = _arr(rows, "correct"); isyes = np.array([r["answer"] == "yes" for r in rows], float)
    conf = _arr(rows, "conf"); py = _arr(rows, "p_yes")
    o, p = y == 1, y == 0
    out = {}; boots = {}
    def put(k, full, boot):
        ci = M.ci(boot) if boot is not None else (math.nan, math.nan)
        out[k] = (float(full), float(ci[0]), float(ci[1]), len(rows)); boots[k] = boot
    def wm(v, mask=None):
        if mask is None:
            return M.wmean(v, w)
        return M.wmean(v[mask], w[:, mask]) if mask.any() else np.full(W.shape[0], np.nan)
    ao, ap = wm(corr, o), wm(corr, p)
    put("acc_orig", corr[o].mean() if o.any() else math.nan, ao)
    put("acc_pert", corr[p].mean() if p.any() else math.nan, ap)
    put("acc_merged", corr.mean(), wm(corr))
    put("bal_acc", (corr[o].mean() + corr[p].mean()) / 2 if o.any() and p.any() else math.nan, (ao + ap) / 2)
    put("frac_yes", isyes.mean(), wm(isyes))
    put("mean_conf", conf.mean(), wm(conf))
    put("mean_pyes", py.mean(), wm(py))
    put("auroc", M.auroc(py, y)[0], M.auroc(py, y, w))
    put("ece", M.ece(py, y)[0], M.ece(py, y, w))
    put("brier", M.brier(py, y)[0], M.brier(py, y, w))
    put("ece_c", M.ece(conf, corr)[0], M.ece(conf, corr, w))
    put("brier_c", M.brier(conf, corr)[0], M.brier(conf, corr, w))
    if cond == "base":
        out["echo_rate"] = (math.nan, math.nan, math.nan, len(rows))
    else:
        echo = (np.abs(conf - cond / 100.0) <= 0.05).astype(float)
        put("echo_rate", echo.mean(), wm(echo))
    return out, boots


def slope_stats(rows_by_x, W, ev_index, key):
    """OLS slope of the weighted mean of `key` on X/100 across the injected X, with bootstrap CI.
    Also returns the X=90 minus X=10 difference."""
    xs = [x for x in C.XS if rows_by_x.get(x)]
    if len(xs) < 3:
        return dict(slope=math.nan, lo=math.nan, hi=math.nan, d90_10=math.nan, d_lo=math.nan, d_hi=math.nan, p=math.nan)
    xv = np.array(xs, float) / 100; xc = xv - xv.mean()
    pts, boots = [], []
    for x in xs:
        rows = rows_by_x[x]; idx = np.array([ev_index[r["id"]] for r in rows])
        v = np.array([r["answer"] == "yes" for r in rows], float) if key == "isyes" else _arr(rows, key)
        pts.append(v.mean()); boots.append(M.wmean(v, W[:, idx]))
    pts = np.array(pts); boots = np.array(boots)          # (k,), (k, B)
    slope = float((xc * pts).sum() / (xc ** 2).sum())
    bs = (xc[:, None] * boots).sum(0) / (xc ** 2).sum()
    d = float(pts[-1] - pts[0]) if xs[0] == 10 and xs[-1] == 90 else math.nan
    db = boots[-1] - boots[0]
    lo, hi = M.ci(bs); dlo, dhi = M.ci(db)
    return dict(slope=slope, lo=float(lo), hi=float(hi), d90_10=d, d_lo=float(dlo), d_hi=float(dhi), p=float(M.boot_p(bs)))


def fmt(v, d=3):
    return "—" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.{d}f}"


def fmtp(v, B):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "—"
    return f"< {2.0 / B:.3g}" if v <= 2.0 / B else f"{v:.3f}"


def cell(pt, lo, hi, n, d=3):
    if n < MIN_N or math.isnan(pt):
        return f"— (n={n})" if n else "—"
    return f"{fmt(pt, d)} [{fmt(lo, d)}, {fmt(hi, d)}]"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--B", type=int, default=2000); ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    sample = C.load_sample(); ids = sample["ids"]; ev_index = {i: k for k, i in enumerate(ids)}
    rng = np.random.default_rng(a.seed)
    W = np.apply_along_axis(np.bincount, 1, rng.integers(0, len(ids), (a.B, len(ids))), minlength=len(ids)).astype(float)
    all_rows = {}; results = {}; cov = {}; slopes = {}; part_slopes = {}; deltas = {}
    ran = []
    for mk in C.ORDER:
        if not C.MODELS[mk]["provider"]:
            continue
        rows = item_table(mk); all_rows[mk] = rows
        by = defaultdict(list)
        for r in rows: by[r["cond"]].append(r)
        have_sweep = any(r["status"] != "not_run" for c in C.XS for r in by[c])
        if have_sweep: ran.append(mk)
        # coverage
        cov[mk] = {c: dict(n_items=len(by[c]), valid_ans=sum(r["valid_ans"] for r in by[c]), valid_conf=sum(r["valid_conf"] for r in by[c]),
                            status={s: sum(r["status"] == s for r in by[c]) for s in sorted({r["status"] for r in by[c]})}) for c in CONDS}
        conds = ["base"] + [x for x in C.XS if any(r["status"] != "not_run" for r in by[x])]
        # common set: events with valid answer + conf in both variants under every available condition
        ok = defaultdict(lambda: True)
        for c in conds:
            for r in by[c]:
                if not r["valid_conf"]:
                    ok[r["id"]] = False
        common = {i for i in ids if ok[i]}
        cov[mk]["common_events"] = len(common); cov[mk]["conds"] = conds
        res = {"common": {}, "all_valid": {}}; bt = {}
        for c in conds:
            res["common"][c], bt[c] = compute_metrics([r for r in by[c] if r["id"] in common], W, ev_index, c)
            res["all_valid"][c], _ = compute_metrics([r for r in by[c] if r["valid_conf"]], W, ev_index, c)
        results[mk] = res
        dl = {}
        for c in conds:
            if c == "base": continue
            dl[c] = {}
            for k, _ in METRICS:
                if k == "echo_rate" or k not in bt.get(c, {}) or k not in bt.get("base", {}): continue
                d = res["common"][c][k][0] - res["common"]["base"][k][0]; db = bt[c][k] - bt["base"][k]
                lo, hi = M.ci(db); dl[c][k] = (float(d), float(lo), float(hi), float(M.boot_p(db)))
        deltas[mk] = dl
        rbx = {x: [r for r in by[x] if r["id"] in common] for x in C.XS if x in conds}
        slopes[mk] = {"frac_yes": slope_stats(rbx, W, ev_index, "isyes"), "mean_pyes": slope_stats(rbx, W, ev_index, "p_yes"),
                      "mean_conf": slope_stats(rbx, W, ev_index, "conf"), "bal_acc_note": "see curves",
                      "n_common": len(common)}
        # by partition (C.partition rule against the model's own cutoff), common set
        ps = {}
        for part in ("pre", "post"):
            sel = {i for i in common if C.partition(sample["events"][i]["publication_date"], C.MODELS[mk]["cutoff"]) == part}
            rb = {x: [r for r in rbx[x] if r["id"] in sel] for x in rbx}
            ps[part] = dict(n_events=len(sel), frac_yes=slope_stats(rb, W, ev_index, "isyes"), mean_pyes=slope_stats(rb, W, ev_index, "p_yes"),
                            base_frac_yes=(np.mean([r["answer"] == "yes" for r in by["base"] if r["id"] in sel]) if sel else math.nan))
        part_slopes[mk] = ps
    # ---------------------------------------------------------------- outputs.jsonl (one record per item per model per X)
    with open(C.OUTPUTS, "w", encoding="utf-8") as f:
        for mk in ran:
            sw = load_sweep(mk)
            for x in C.XS:
                for i in ids:
                    for task in ("binary", "binary_perturbed"):
                        r = sw.get((x, i, task))
                        if r is not None:
                            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    # ---------------------------------------------------------------- tables
    C.TABLES.mkdir(exist_ok=True)
    names = {mk: C.MODELS[mk]["name"] for mk in C.MODELS}
    csv = ["model,item_set,cond,metric,value,ci_lo,ci_hi,n_items"]
    for mk, res in results.items():
        for st_, d in res.items():
            for c, mm in d.items():
                for k, _ in METRICS:
                    v = mm[k]; csv.append(f"{names[mk]},{st_},{c},{k},{fmt(v[0],5)},{fmt(v[1],5)},{fmt(v[2],5)},{v[3]}")
    (C.TABLES / "curves.csv").write_text("\n".join(csv) + "\n")
    for st_ in ("common", "all_valid"):
        md = [f"# Metric curves over the injected base rate X — item set: {st_}\n",
              ("Primary set: events whose both variants have a parsed answer and a confidence in the baseline and at every X (same items at every point)."
               if st_ == "common" else "Sensitivity: all items with a parsed answer and a confidence under that condition (item sets differ across conditions)."),
              f"\nCells: point estimate [{a.B}-draw event-cluster bootstrap percentile 95% CI]; cells with n < {MIN_N} items suppressed. n = items (events x 2 variants). "
              "`base` = the stored no-injection base run, not regenerated.\n"]
        for k, title in METRICS:
            md.append(f"\n## {title} (`{k}`)\n")
            md.append("| model | " + " | ".join(f"X={c}%" if c != "base" else "base (none)" for c in CONDS) + " | n items (base) |")
            md.append("|---|" + "---|" * (len(CONDS) + 1))
            for mk, res in results.items():
                d = res[st_]
                md.append(f"| {names[mk]} | " + " | ".join(cell(*d[c][k]) if c in d else "not run" for c in CONDS) + f" | {d['base'][k][3]} |")
        (C.TABLES / f"curves_{st_}.md").write_text("\n".join(md) + "\n")
    # slopes
    md = ["# Sensitivity to the stated prior: slope of the metric on X (X as a fraction, 0.10 … 0.90)\n",
          "OLS slope across the five injected values on the common item set (baseline excluded), event-cluster bootstrap 95% CI and two-sided percentile p. "
          "A slope near 1 for mean P(Yes) means the model adopts the stated rate almost one-for-one; near 0 means it ignores it. "
          "Δ(90−10) = metric at X=90% minus X=10%.\n",
          "| model | n events (common) | slope frac-Yes [CI] | p | Δ frac-Yes (90−10) [CI] | slope mean P(Yes) [CI] | p | Δ mean P(Yes) (90−10) [CI] | slope mean conf [CI] |",
          "|---|---|---|---|---|---|---|---|---|"]
    csv = ["model,n_common,metric,slope,ci_lo,ci_hi,p,d90_10,d_lo,d_hi"]
    for mk, s in slopes.items():
        if not math.isnan(s["frac_yes"]["slope"]):
            f_, p_, c_ = s["frac_yes"], s["mean_pyes"], s["mean_conf"]
            md.append(f"| {names[mk]} | {s['n_common']} | {fmt(f_['slope'])} [{fmt(f_['lo'])}, {fmt(f_['hi'])}] | {fmtp(f_['p'], a.B)} | {fmt(f_['d90_10'])} [{fmt(f_['d_lo'])}, {fmt(f_['d_hi'])}] "
                      f"| {fmt(p_['slope'])} [{fmt(p_['lo'])}, {fmt(p_['hi'])}] | {fmtp(p_['p'], a.B)} | {fmt(p_['d90_10'])} [{fmt(p_['d_lo'])}, {fmt(p_['d_hi'])}] | {fmt(c_['slope'])} [{fmt(c_['lo'])}, {fmt(c_['hi'])}] |")
            for k in ("frac_yes", "mean_pyes", "mean_conf"):
                v = s[k]; csv.append(f"{names[mk]},{s['n_common']},{k},{fmt(v['slope'],5)},{fmt(v['lo'],5)},{fmt(v['hi'],5)},{fmt(v['p'],5)},{fmt(v['d90_10'],5)},{fmt(v['d_lo'],5)},{fmt(v['d_hi'],5)}")
    (C.TABLES / "slopes.md").write_text("\n".join(md) + "\n"); (C.TABLES / "slopes.csv").write_text("\n".join(csv) + "\n")
    # partition slopes
    md = [f"# Sensitivity by partition (pre / post each model's own cutoff; cutoff month counts as {'pre' if C.CUTOFF_MONTH_PRE else 'post'}), common item set\n",
          f"Slopes of fraction-Yes and mean P(Yes) on X within each partition; partitions with < {MIN_N} events suppressed.\n",
          "| model | cutoff | partition | n events | base frac-Yes | slope frac-Yes [CI] | slope mean P(Yes) [CI] |", "|---|---|---|---|---|---|---|"]
    for mk, ps in part_slopes.items():
        for part, d in ps.items():
            if math.isnan(d["frac_yes"]["slope"]): continue
            if d["n_events"] < MIN_N:
                md.append(f"| {names[mk]} | {C.MODELS[mk]['cutoff']} | {part} | {d['n_events']} | — | — | — |"); continue
            md.append(f"| {names[mk]} | {C.MODELS[mk]['cutoff']} | {part} | {d['n_events']} | {fmt(d['base_frac_yes'])} | {fmt(d['frac_yes']['slope'])} [{fmt(d['frac_yes']['lo'])}, {fmt(d['frac_yes']['hi'])}] | {fmt(d['mean_pyes']['slope'])} [{fmt(d['mean_pyes']['lo'])}, {fmt(d['mean_pyes']['hi'])}] |")
    (C.TABLES / "partition_slopes.md").write_text("\n".join(md) + "\n")
    # coverage
    md = ["# Coverage: items with a parsed answer / a confidence, per condition (1,000 items = 500 events x 2 variants)\n",
          "| model | condition | parsed answer | with confidence | statuses |", "|---|---|---|---|---|"]
    for mk, cv in cov.items():
        for c in CONDS:
            d = cv[c]
            if c != "base" and d["valid_ans"] == 0 and d["status"].get("not_run") == d["n_items"]: continue
            md.append(f"| {names[mk]} | {c} | {d['valid_ans']} | {d['valid_conf']} | {', '.join(f'{k} {v}' for k, v in d['status'].items())} |")
        md.append(f"| {names[mk]} | **common set** | — | — | {cv['common_events']} events with both variants valid under every condition |")
    (C.TABLES / "coverage.md").write_text("\n".join(md) + "\n")
    md = ["# Paired change versus the stored no-injection baseline (common item set)\n",
          f"Δ = metric at X minus metric at baseline on the same items; {a.B}-draw event-cluster bootstrap 95% CI (shared resamples, so the difference is paired) and two-sided percentile p. Not multiplicity-adjusted.\n"]
    for k, title in METRICS:
        if k == "echo_rate": continue
        md.append(f"\n## Δ {title} (`{k}`)\n")
        md.append("| model | " + " | ".join(f"X={x}%" for x in C.XS) + " |"); md.append("|---|" + "---|" * len(C.XS))
        for mk, dl in deltas.items():
            if not dl: continue
            cells = []
            for x in C.XS:
                v = dl.get(x, {}).get(k)
                cells.append("—" if v is None else f"{v[0]:+.3f} [{v[1]:+.3f}, {v[2]:+.3f}] p={fmtp(v[3], a.B)}")
            md.append(f"| {names[mk]} | " + " | ".join(cells) + " |")
    (C.TABLES / "deltas_vs_base.md").write_text("\n".join(md) + "\n")
    json.dump(dict(results=results, slopes=slopes, partition_slopes=part_slopes, coverage=cov, deltas=deltas, B=a.B, seed=a.seed),
              open(C.TABLES / "analysis.json", "w"), indent=1, default=float)
    # ---------------------------------------------------------------- figures
    make_figures(results, slopes, names, ran)
    print("analysis written; models with sweep data:", [names[m] for m in ran])


def make_figures(results, slopes, names, ran):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    C.FIGS.mkdir(exist_ok=True)
    models = [m for m in results if m in ran] or list(results)
    if not models: return
    palette = ["#1f77b4", "#d62728", "#2ca02c", "#9467bd", "#ff7f0e", "#17becf", "#8c564b", "#e377c2", "#7f7f7f", "#bcbd22"]
    col = {m: palette[i % len(palette)] for i, m in enumerate(models)}
    xs = np.array(C.XS)
    for k, title in METRICS:
        # (a) small multiples: one panel per model, baseline as dashed line + CI band
        n = len(models); nc = 3; nr = math.ceil(n / nc)
        fig, axes = plt.subplots(nr, nc, figsize=(3.6 * nc, 2.9 * nr), sharex=True, sharey=True, squeeze=False)
        for ax, m in zip(axes.flat, models):
            d = results[m]["common"]
            pts = [d[x][k] if x in d else (math.nan,) * 4 for x in C.XS]
            y = np.array([p[0] for p in pts]); lo = np.array([p[1] for p in pts]); hi = np.array([p[2] for p in pts])
            ax.fill_between(xs, lo, hi, color=col[m], alpha=0.18, linewidth=0)
            ax.plot(xs, y, "-o", color=col[m], ms=4, lw=1.6)
            b = d["base"][k]
            ax.axhline(b[0], color="#444", ls="--", lw=1)
            ax.axhspan(b[1], b[2], color="#444", alpha=0.08, linewidth=0)
            ax.set_title(f"{names[m]}  (n={d['base'][k][3]})", fontsize=9)
            if k in ("frac_yes", "mean_pyes"):
                ax.plot([10, 90], [0.1, 0.9], ":", color="#999", lw=1)
            ax.grid(alpha=0.25); ax.set_xticks(C.XS)
        for ax in axes.flat[len(models):]: ax.axis("off")
        for ax in axes[-1]: ax.set_xlabel("injected base rate X (%)")
        for ax in axes[:, 0]: ax.set_ylabel(k)
        fig.suptitle(f"{title} — dashed: stored no-injection baseline (band = 95% CI)" + ("; dotted: y = X" if k in ("frac_yes", "mean_pyes") else ""), fontsize=10)
        fig.tight_layout(rect=(0, 0, 1, 0.96)); fig.savefig(C.FIGS / f"{k}_panels.png", dpi=150); plt.close(fig)
        # (b) overlay, one line per model, baseline marked at x = "none"
        fig, ax = plt.subplots(figsize=(7.2, 4.4))
        for m in models:
            d = results[m]["common"]
            y = [d[x][k][0] if x in d else math.nan for x in C.XS]
            ax.plot(xs, y, "-o", color=col[m], ms=3.5, lw=1.5, label=names[m])
            ax.plot([-10], [d["base"][k][0]], marker="s", color=col[m], ms=5)
