def f(v, d=3): return "—" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.{d}f}"
def fp(v): return "—" if v is None or math.isnan(v) else (f"< {2/B:.3g}" if v <= 2 / B else f"{v:.3f}")
def m(k, cond, metric): return res[k][str(cond)][metric]          # (pt, lo, hi, n)
def ci(t, d=3): return f"{f(t[0], d)} [{f(t[1], d)}, {f(t[2], d)}]"
def dcell(k, x, metric):
    v = dl[k].get(str(x), {}).get(metric); return "—" if v is None else f"{v[0]:+.3f} [{v[1]:+.3f}, {v[2]:+.3f}], p {fp(v[3])}"
def sig(k, x, metric, sign=None):
    v = dl[k].get(str(x), {}).get(metric)
    if v is None: return False
    ok = v[3] < 0.05 and not (v[1] <= 0 <= v[2])
    return ok and (sign is None or (v[0] > 0) == (sign > 0))
def monotone(k, metric):
    v = [m(k, x, metric)[0] for x in XS]; return all(b >= a for a, b in zip(v, v[1:]))


def curve_table(metric, d=3, extra=None):
    rows = ["| model | base (none) | " + " | ".join(f"X={x}%" for x in XS) + (" | " + extra[0] if extra else "") + " | n items |",
            "|---|---|" + "---|" * len(XS) + ("---|" if extra else "")]
    for k in ran:
        r = f"| {names[k]} | {ci(m(k, 'base', metric), d)} | " + " | ".join(ci(m(k, x, metric), d) for x in XS)
        if extra: r += " | " + extra[1](k)
        rows.append(r + f" | {m(k, 'base', metric)[3]} |")
    return "\n".join(rows)


def slope_str(k, metric):
    s = sl[k][metric]; return f"{f(s['slope'], 2)} [{f(s['lo'], 2)}, {f(s['hi'], 2)}]"


